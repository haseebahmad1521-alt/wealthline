// One-time export of the old Bilt backend into a SQL seed for the new Supabase schema.
// Usage: node --env-file=.env supabase/import/bilt.mjs
// Reads BILT_URL / BILT_ANON_KEY (public, read-only via RLS). Writes supabase/import/bilt-import.sql
// and prints a summary. Nothing is invented: rows are copied as-is, ids preserved.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const base = process.env.BILT_URL?.replace(/\/+$/, '');
const key = process.env.BILT_ANON_KEY;
if (!base || !key) {
  console.error('Set BILT_URL and BILT_ANON_KEY in .env first.');
  process.exit(1);
}

async function table(name, order) {
  const rows = [];
  for (let from = 0; ; from += 1000) {
    const res = await fetch(`${base}/rest/v1/${name}?select=*&order=${order}`, {
      headers: { apikey: key, Authorization: `Bearer ${key}`, Range: `${from}-${from + 999}` },
    });
    if (!res.ok) throw new Error(`${name}: HTTP ${res.status} ${await res.text()}`);
    const page = await res.json();
    rows.push(...page);
    if (page.length < 1000) return rows;
  }
}

// Portrait credits lived in the old app's source, not its database: read them from the main branch.
function portraits() {
  const src = execFileSync('git', ['show', 'main:lib/portraits.ts'], { encoding: 'utf8' });
  const out = {};
  const re = /'([a-z0-9-]+)':\s*portrait\(\s*'([^']+)',\s*'([^']+)',\s*'([^']+)',\s*'([^']+)',\s*'([^']+)',?\s*\)/g;
  for (const [, slug, path, file, author, license, licenseUrl] of src.matchAll(re)) {
    out[slug] = {
      portrait_url: `https://thumb.wikimedia.org/wikipedia/commons/thumb/${path}/960px-${file}`,
      portrait_page_url: `https://commons.wikimedia.org/wiki/File:${file}`,
      portrait_author: author,
      portrait_license: license,
      portrait_license_url: licenseUrl,
    };
  }
  return out;
}

const q = (v) => (v == null ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replaceAll("'", "''")}'`);
const insert = (t, rows, cols) =>
  rows.length
    ? `insert into public.${t} (${cols.join(', ')}) values\n${rows.map((r) => `  (${cols.map((c) => q(r[c])).join(', ')})`).join(',\n')}\non conflict do nothing;\n`
    : `-- no ${t} rows\n`;

const [people, snapshots, holdings, projects, events] = await Promise.all([
  table('billionaires', 'rank'),
  table('net_worth_snapshots', 'timestamp'),
  table('holdings', 'id'),
  table('projects', 'announced_date'),
  table('events', 'date'),
]);
const credit = portraits();

const placeholders = people.filter((p) => !p.name);
const personRows = people.filter((p) => p.name).map((p) => ({
  id: p.id,
  slug: p.slug,
  name: p.name,
  age: p.age,
  residence: p.residence,
  citizenship: p.citizenship,
  main_source: p.main_source,
  bio: p.bio,
  other_assets_usd: p.other_assets_usd ?? 0,
  ...credit[p.slug],
}));

// Every Bilt snapshot is a dated owner estimate (monthly, at US market close); the old
// updater never wrote rows. 'estimate' also means the app never projects them as live.
const valueRows = snapshots.map((s) => ({
  id: s.id,
  person_id: s.billionaire_id,
  as_of: new Date(s.timestamp).toISOString(),
  net_worth_usd: Number(s.net_worth_usd),
  kind: 'estimate',
  source_label: 'Owner-supplied estimate (imported from Bilt)',
  source_url: null,
}));
const withPerson = (r) => ({ ...r, person_id: r.billionaire_id });

const sql = [
  `-- Generated by supabase/import/bilt.mjs on ${new Date().toISOString()}. Do not edit by hand.`,
  'begin;',
  insert('people', personRows, ['id', 'slug', 'name', 'age', 'residence', 'citizenship', 'main_source', 'bio', 'other_assets_usd', 'portrait_url', 'portrait_page_url', 'portrait_author', 'portrait_license', 'portrait_license_url']),
  insert('net_worth_values', valueRows, ['id', 'person_id', 'as_of', 'net_worth_usd', 'kind', 'source_label', 'source_url']),
  insert('holdings', holdings.map(withPerson), ['id', 'person_id', 'company', 'ticker', 'shares_owned', 'stake_percent', 'role', 'is_private', 'private_valuation_usd']),
  insert('projects', projects.map(withPerson), ['id', 'person_id', 'title', 'description', 'status', 'announced_date', 'source_name', 'source_url']),
  insert('events', events.map(withPerson), ['id', 'person_id', 'date', 'text']),
  'commit;',
].join('\n');

const out = new URL('./bilt-import.sql', import.meta.url);
writeFileSync(out, sql);
console.log(`people ${personRows.length} (skipped ${placeholders.length} nameless placeholders; portrait credits matched: ${personRows.filter((p) => p.portrait_url).length})`);
const full = personRows.filter((p) => valueRows.some((v) => v.person_id === p.id && Number(p.other_assets_usd) >= v.net_worth_usd));
if (full.length) console.log(`WARNING: ${full.length} people have other_assets_usd >= their net worth; calibrate before enabling the market updater (double-counting).`);
console.log(`values ${valueRows.length} (all dated estimates)`);
console.log(`holdings ${holdings.length}, projects ${projects.length}, events ${events.length}`);
console.log(`wrote ${out.pathname}\nReview it, then run it in the Supabase SQL editor (after both migrations).`);
