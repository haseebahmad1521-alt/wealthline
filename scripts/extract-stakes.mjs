// Builds src/data/stakes.json from supabase/import/ownership.sql: the share counts ownership.mjs found in SEC filings
// (Form 4 or Schedule 13G/13D) for tracked people in their US-listed companies. The app uses them wherever the
// database has no recorded stake for that person and company yet; applying ownership.sql puts them in the database.
// Run: node scripts/extract-stakes.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const sql = readFileSync('supabase/import/ownership.sql', 'utf8');
const generated = sql.match(/generated by ownership\.mjs on (\d{4}-\d{2}-\d{2})/)?.[1] ?? null;
// One value: 'quoted text' (with '' escapes), a number, or null.
const value = String.raw`('(?:[^']|'')*'|-?\d+(?:\.\d+)?|null)`;
const insert = new RegExp(
  String.raw`insert into public\.holdings \(person_id, company, ticker, company_id, shares_owned, shares_source_label, shares_source_url, shares_as_of, shares_note\) select ` +
    Array.from({ length: 9 }, () => value).join(', '),
  'g',
);
const unq = (v) => (v === 'null' ? null : v.startsWith("'") ? v.slice(1, -1).replace(/''/g, "'") : Number(v));

const stakes = [];
for (const m of sql.matchAll(insert)) {
  const [person_id, company, ticker, company_id, shares, label, url, as_of, note] = m.slice(1).map(unq);
  if (!(shares > 0)) continue;
  stakes.push({ person_id, company_id, company, ticker, shares, label, url, as_of, note });
}
writeFileSync('src/data/stakes.json', `${JSON.stringify({ generated, source: 'supabase/import/ownership.sql (SEC Form 4 and Schedule 13G/13D)', stakes }, null, 1)}\n`);
console.log(`${stakes.length} stakes from ownership.sql (${generated})`);
for (const s of stakes) console.log(`  ${s.company.padEnd(30)} ${Math.round(s.shares).toLocaleString('en-US').padStart(15)}  ${s.label}`);
